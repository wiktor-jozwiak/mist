#!/usr/bin/env python3
"""docs/img/memory.svg from a bench/shells.sh result: idle PSS per shell, median bar, range as a lighter bar.
    chart.py bench/results/shells-<date>.jsonl > docs/img/memory.svg"""
import json, statistics, sys
from collections import defaultdict
from html import escape

rows = [json.loads(l) for l in open(sys.argv[1]) if l.strip()]
by, order = defaultdict(list), []
for d in rows:
    if d["scenario"] != "idle":
        continue
    if d["shell"] not in order:
        order.append(d["shell"])
    by[d["shell"]].append(d)

bars = []  # (label, lo, med, hi, note, mist)
for s in order:
    pss = [d["total"]["pss"] for d in by[s]]
    gpu = statistics.median(d["total"]["gpu"] for d in by[s])
    note = f"{statistics.median(pss):.0f} MB" + (f" · {gpu:.0f} MiB GPU" if gpu else " · no GPU memory")
    bars.append(("Mist, live wallpaper" if s == "Mist" else s, min(pss), statistics.median(pss), max(pss), note, s == "Mist"))
    if s == "Mist":  # the UI process without the live wallpaper's renderer
        ui = [sum(p["pss"] for p in d["procs"] if p["comm"] != "mist-wall") for d in by[s]]
        bars.append(("Mist without mist-wall", min(ui), statistics.median(ui), max(ui),
                     f"{statistics.median(ui):.0f} MB · no GPU memory", True))
bars.sort(key=lambda b: b[2])

top, step, x0, w = 64, 40, 250, 820
scale = 380 / max(b[3] for b in bars)
h = top + step * len(bars) + 26
out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">',
       f'  <!-- generated by bench/chart.py from {escape(sys.argv[1].rsplit('/', 1)[-1])}: idle PSS of each shell\'s process tree, median of the runs -->',
       f'  <rect width="{w}" height="{h}" rx="16" fill="#16131a"/>',
       '  <g font-family="-apple-system, Segoe UI, Inter, Helvetica, Arial, sans-serif" font-size="14">',
       '    <text x="24" y="34" font-size="15" font-weight="600" fill="#f2ece6">Idle memory, whole shell (PSS)</text>',
       '    <text x="796" y="34" text-anchor="end" fill="#8d8590">headless sway · RTX 4060 · two 1080p outputs</text>']
for i, (label, lo, med, hi, note, mist) in enumerate(bars):
    y = top + i * step
    fg = "#f2ece6" if mist else "#c9c1c6"
    col = "#f0a060" if mist else "#6b6370"
    out.append(f'    <text x="24" y="{y + 14}" fill="{fg}"{" font-weight=\"600\"" if mist else ""}>{escape(label)}</text>')
    if hi > med:
        out.append(f'    <rect x="{x0}" y="{y}" width="{max(hi * scale, 4):.0f}" height="20" rx="5" fill="{col}" opacity="0.4"/>')
    out.append(f'    <rect x="{x0}" y="{y}" width="{max(med * scale, 4):.0f}" height="20" rx="5" fill="{col}"/>')
    out.append(f'    <text x="{x0 + max(hi * scale, 4) + 8:.0f}" y="{y + 15}" fill="{fg}">{escape(note)}</text>')
out.append(f'    <text x="24" y="{h - 16}" font-size="12" fill="#8d8590">Each shell alone, its packaged default configuration, {len(by[order[0]])} runs. Method and every number: docs/BENCHMARKS.md</text>')
out += ['  </g>', '</svg>']
print("\n".join(out))
